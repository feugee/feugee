export interface SocialLink {
  id: string;
  url: string;
  label: string;
  Icon: ComponentType;
}

/**
 * The Footer's Social Links resolved for render: a row renders only when its
 * platform lookup hits the icon map above and its URL is filled. The select
 * is typed, but a platform removed from the vocabulary can survive in older
 * data — an unknown value drops the row rather than rendering a broken link.
 */
export const toSocialLinks = (links: Footer["socialLinks"]): SocialLink[] =>
  (links ?? []).flatMap((link) => {
    const platform = socialPlatforms[link.platform];
    const url = link.url.trim();
    if (platform === undefined || url === "") return [];
    return [
      { id: link.id ?? link.url, url, label: platform.label, Icon: platform.Icon },
    ];
  });
